CREATE SCHEMA IF NOT EXISTS payments;

CREATE TABLE payments.payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    booking_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    coupon_id BIGINT NULL,

    booking_amount DECIMAL(12,2) NOT NULL,
    discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    final_amount DECIMAL(12,2) NOT NULL,
    amount_paid DECIMAL(12,2) NOT NULL DEFAULT 0.00,

    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    payment_status VARCHAR(30) NOT NULL DEFAULT 'CREATED',

    paid_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payment
        PRIMARY KEY (payment_id),

    CONSTRAINT uk_payment_booking
        UNIQUE (booking_id),

    CONSTRAINT chk_payment_booking_amount
        CHECK (booking_amount >= 0),

    CONSTRAINT chk_payment_discount_amount
        CHECK (
            discount_amount >= 0
            AND discount_amount <= booking_amount
        ),

    CONSTRAINT chk_payment_final_amount
        CHECK (
            final_amount >= 0
            AND final_amount = booking_amount - discount_amount
        ),

    CONSTRAINT chk_payment_amount_paid
        CHECK (
            amount_paid >= 0
            AND amount_paid <= final_amount
        ),

    CONSTRAINT chk_payment_currency
        CHECK (currency ~ '^[A-Z]{3}$'),

    CONSTRAINT chk_payment_status
        CHECK (
            payment_status IN (
                'CREATED',
                'PENDING',
                'PAID',
                'FAILED',
                'CANCELLED',
                'PARTIALLY_REFUNDED',
                'REFUNDED'
            )
        )
);


CREATE TABLE payments.payment_transaction (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_id BIGINT NOT NULL,

    gateway_transaction_id VARCHAR(150) NOT NULL,
    attempt_number INT NOT NULL,

    payment_method VARCHAR(40) NOT NULL,
    payment_gateway VARCHAR(50) NOT NULL,

    transaction_amount DECIMAL(12,2) NOT NULL,
    transaction_status VARCHAR(30) NOT NULL DEFAULT 'INITIATED',
    response_code VARCHAR(50),

    initiated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP NULL,

    CONSTRAINT pk_payment_transaction
        PRIMARY KEY (transaction_id),

    CONSTRAINT fk_transaction_payment
        FOREIGN KEY (payment_id)
        REFERENCES payments.payment(payment_id),

    CONSTRAINT uk_gateway_transaction
        UNIQUE (gateway_transaction_id),

    CONSTRAINT uk_payment_attempt
        UNIQUE (payment_id, attempt_number),

    CONSTRAINT chk_transaction_attempt
        CHECK (attempt_number > 0),

    CONSTRAINT chk_transaction_amount
        CHECK (transaction_amount > 0),

    CONSTRAINT chk_transaction_method
        CHECK (
            payment_method IN (
                'UPI',
                'CARD',
                'NET_BANKING',
                'WALLET'
            )
        ),

    CONSTRAINT chk_transaction_status
        CHECK (
            transaction_status IN (
                'INITIATED',
                'PENDING',
                'SUCCESS',
                'FAILED'
            )
        )
);


CREATE TABLE payments.refund (
    refund_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_id BIGINT NOT NULL,
    transaction_id BIGINT NOT NULL,

    gateway_refund_id VARCHAR(150) NOT NULL,
    refund_amount DECIMAL(12,2) NOT NULL,
    refund_reason VARCHAR(255) NOT NULL,
    refund_status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',

    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMP NULL,

    CONSTRAINT pk_refund
        PRIMARY KEY (refund_id),

    CONSTRAINT fk_refund_payment
        FOREIGN KEY (payment_id)
        REFERENCES payments.payment(payment_id),

    CONSTRAINT fk_refund_transaction
        FOREIGN KEY (transaction_id)
        REFERENCES payments.payment_transaction(transaction_id),

    CONSTRAINT uk_gateway_refund
        UNIQUE (gateway_refund_id),

    CONSTRAINT chk_refund_amount
        CHECK (refund_amount > 0),

    CONSTRAINT chk_refund_status
        CHECK (
            refund_status IN (
                'REQUESTED',
                'PROCESSING',
                'SUCCESS',
                'FAILED',
                'REJECTED'
            )
        )
);


CREATE INDEX idx_payment_user_id
    ON payments.payment(user_id);

CREATE INDEX idx_payment_coupon_id
    ON payments.payment(coupon_id);

CREATE INDEX idx_payment_status
    ON payments.payment(payment_status);

CREATE INDEX idx_transaction_payment_id
    ON payments.payment_transaction(payment_id);

CREATE INDEX idx_transaction_status
    ON payments.payment_transaction(transaction_status);

CREATE INDEX idx_refund_payment_id
    ON payments.refund(payment_id);

CREATE INDEX idx_refund_transaction_id
    ON payments.refund(transaction_id);

CREATE INDEX idx_refund_status
    ON payments.refund(refund_status);


CREATE OR REPLACE FUNCTION payments.set_payment_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


CREATE TRIGGER trg_payment_updated_at
BEFORE UPDATE ON payments.payment
FOR EACH ROW
EXECUTE FUNCTION payments.set_payment_updated_at();


COMMENT ON COLUMN payments.payment.booking_id IS
'Logical reference to booking.booking_id. Physical foreign key will be added when the Booking module is integrated.';

COMMENT ON COLUMN payments.payment.user_id IS
'Logical reference to user_profile.user_id. Physical foreign key will be added when the User module is integrated.';

COMMENT ON COLUMN payments.payment.coupon_id IS
'Optional logical reference to coupon.coupon_id. Physical foreign key will be added when the Coupon module is integrated.';